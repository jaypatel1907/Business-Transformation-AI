    if (/table|book|reserv|schedule|appointment/.test(t)) return "📅";
    if (/menu|dish|food|pizza|burger|kitchen|drink/.test(t)) return "🍲";
    if (/pay|bill|wallet|invoice|money|checkout/.test(t)) return "💳";
